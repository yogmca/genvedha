/**
 * Code Customizer
 * Applies AI-generated customizations to the template code
 */

const fs = require('fs-extra');
const path = require('path');

class CodeCustomizer {
  /**
   * Apply customizations to the copied template
   * @param {Object} params - Customization parameters
   * @param {string} params.appPath - Path to the app
   * @param {Object} params.customizations - Customization data
   * @param {Array} params.templateFiles - List of template files
   * @returns {Promise<Object>} Customization results
   */
  async applyCustomizations(params) {
    const { appPath, customizations } = params;

    try {
      console.log('✏️  Applying code customizations...');

      const results = {
        filesModified: 0,
        filesCreated: 0,
        errors: []
      };

      // Apply branding changes
      await this._applyBrandingChanges(appPath, customizations.brandingChanges);
      results.filesModified += 3;

      // Update configuration files
      await this._updateConfigFiles(appPath, customizations);
      results.filesModified += 2;

      // Apply feature customizations
      await this._applyFeatureCustomizations(appPath, customizations.features);
      results.filesModified += 1;

      // Update SEO metadata
      await this._updateSEOMetadata(appPath, customizations.seoConfig);
      results.filesModified += 1;

      console.log(`✅ Customizations applied: ${results.filesModified} files modified`);
      return results;

    } catch (error) {
      console.error('❌ Failed to apply customizations:', error.message);
      throw error;
    }
  }

  /**
   * Apply branding changes (colors, company name, etc.)
   */
  async _applyBrandingChanges(appPath, brandingChanges) {
    try {
      console.log('🎨 Applying branding changes...');

      // Update package.json with company name
      const packageJsonPath = path.join(appPath, 'package.json');
      if (await fs.pathExists(packageJsonPath)) {
        const packageJson = await fs.readJson(packageJsonPath);
        packageJson.author = brandingChanges.companyName;
        await fs.writeJson(packageJsonPath, packageJson, { spaces: 2 });
      }

      // Update public/index.html with branding
      const indexHtmlPath = path.join(appPath, 'public', 'index.html');
      if (await fs.pathExists(indexHtmlPath)) {
        let html = await fs.readFile(indexHtmlPath, 'utf-8');
        
        // Update title
        html = html.replace(/<title>.*?<\/title>/, `<title>${brandingChanges.companyName}</title>`);
        
        // Update meta description if exists
        if (html.includes('name="description"')) {
          html = html.replace(
            /name="description" content=".*?"/,
            `name="description" content="${brandingChanges.tagline || brandingChanges.companyName}"`
          );
        }
        
        await fs.writeFile(indexHtmlPath, html);
      }

      // Create/update CSS variables for colors
      const cssVarsPath = path.join(appPath, 'src', 'styles', 'variables.css');
      await fs.ensureDir(path.dirname(cssVarsPath));
      
      const cssVars = `:root {
  /* Brand Colors - Generated by GenVedha */
  --primary-color: ${brandingChanges.primaryColor || '#0066ff'};
  --secondary-color: ${brandingChanges.secondaryColor || '#ff6b35'};
  --company-name: "${brandingChanges.companyName}";
  
  /* Derived Colors */
  --primary-light: ${this._lightenColor(brandingChanges.primaryColor || '#0066ff', 20)};
  --primary-dark: ${this._darkenColor(brandingChanges.primaryColor || '#0066ff', 20)};
}
`;
      
      await fs.writeFile(cssVarsPath, cssVars);

      console.log('✅ Branding changes applied');
    } catch (error) {
      console.warn('⚠️  Some branding changes failed:', error.message);
    }
  }

  /**
   * Update configuration files
   */
  async _updateConfigFiles(appPath, customizations) {
    try {
      console.log('⚙️  Updating configuration files...');

      // Create app config
      const appConfigPath = path.join(appPath, 'src', 'config', 'app-config.json');
      await fs.ensureDir(path.dirname(appConfigPath));
      
      const appConfig = {
        appName: customizations.appName,
        businessType: customizations.businessType,
        branding: customizations.brandingChanges,
        features: customizations.features,
        categories: customizations.productCategories,
        generatedBy: 'GenVedha LLM Service',
        generatedAt: new Date().toISOString()
      };
      
      await fs.writeJson(appConfigPath, appConfig, { spaces: 2 });

      console.log('✅ Configuration files updated');
    } catch (error) {
      console.warn('⚠️  Some config updates failed:', error.message);
    }
  }

  /**
   * Apply feature customizations
   */
  async _applyFeatureCustomizations(appPath, features) {
    try {
      console.log('🔧 Applying feature customizations...');

      const featuresConfigPath = path.join(appPath, 'src', 'config', 'features.json');
      await fs.ensureDir(path.dirname(featuresConfigPath));
      
      await fs.writeJson(featuresConfigPath, features || {}, { spaces: 2 });

      console.log('✅ Feature customizations applied');
    } catch (error) {
      console.warn('⚠️  Feature customizations failed:', error.message);
    }
  }

  /**
   * Update SEO metadata
   */
  async _updateSEOMetadata(appPath, seoConfig) {
    try {
      console.log('🔍 Updating SEO metadata...');

      if (!seoConfig) return;

      const indexHtmlPath = path.join(appPath, 'public', 'index.html');
      if (await fs.pathExists(indexHtmlPath)) {
        let html = await fs.readFile(indexHtmlPath, 'utf-8');
        
        const metaTags = `
    <meta name="description" content="${seoConfig.metaDescription || ''}">
    <meta name="keywords" content="${(seoConfig.keywords || []).join(', ')}">`;

        if (html.includes('</head>')) {
          html = html.replace('</head>', `${metaTags}\n  </head>`);
          await fs.writeFile(indexHtmlPath, html);
        }
      }

      console.log('✅ SEO metadata updated');
    } catch (error) {
      console.warn('⚠️  SEO updates failed:', error.message);
    }
  }

  _lightenColor(hex, percent) {
    const num = parseInt(hex.replace('#', ''), 16);
    const amt = Math.round(2.55 * percent);
    const R = Math.min(255, (num >> 16) + amt);
    const G = Math.min(255, (num >> 8 & 0x00FF) + amt);
    const B = Math.min(255, (num & 0x0000FF) + amt);
    return '#' + ((R << 16) + (G << 8) + B).toString(16).padStart(6, '0');
  }

  _darkenColor(hex, percent) {
    const num = parseInt(hex.replace('#', ''), 16);
    const amt = Math.round(2.55 * percent);
    const R = Math.max(0, (num >> 16) - amt);
    const G = Math.max(0, (num >> 8 & 0x00FF) - amt);
    const B = Math.max(0, (num & 0x0000FF) - amt);
    return '#' + ((R << 16) + (G << 8) + B).toString(16).padStart(6, '0');
  }
}

module.exports = CodeCustomizer;
