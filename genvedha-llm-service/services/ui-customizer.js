  /**
   * Get theme for a business type — auto-generates unique colors if not in the library
   * @param {string} businessType - The type of business
   * @param {string} businessName - The business name (used for deterministic color generation)
   * @returns {Object} Theme configuration
   */
  getThemeForBusinessType(businessType, businessName = '') {
    const normalizedType = (businessType || 'general').toLowerCase().replace(/\s+/g, '_');
    
    // Check if we have a predefined theme
    if (this.businessTypeTemplates[normalizedType]) {
      return this.businessTypeTemplates[normalizedType];
    }
    
    // Check for partial matches (e.g., "aquatic plants" matches "aquatic_plants")
    for (const [key, theme] of Object.entries(this.businessTypeTemplates)) {
      if (normalizedType.includes(key) || key.includes(normalizedType)) {
        return theme;
      }
    }
    
    // Auto-generate a unique theme based on the business name hash
    return this._generateUniqueTheme(businessName || businessType);
  }

  /**
   * Generate a unique, visually appealing color theme from a string
   * Uses a deterministic hash so the same business always gets the same colors
   */
  _generateUniqueTheme(seed) {
    // Simple hash function for deterministic color generation
    let hash = 0;
    for (let i = 0; i < seed.length; i++) {
      const char = seed.charCodeAt(i);
      hash = ((hash << 5) - hash) + char;
      hash = hash & hash; // Convert to 32-bit integer
    }
    
    // Generate a hue from the hash (0-360)
    const hue = Math.abs(hash % 360);
    
    // Use golden ratio to generate a complementary secondary hue
    const secondaryHue = (hue + 137) % 360; // Golden angle ≈ 137.5°
    
    // Convert HSL to hex with good saturation and lightness for brand colors
    const primaryColor = this._hslToHex(hue, 65, 40);
    const secondaryColor = this._hslToHex(secondaryHue, 60, 45);
    
    return {
      layout: 'grid',
      primaryColor,
      secondaryColor,
      emoji: '🛍️',
      autoGenerated: true
    };
  }

  /**
   * Convert HSL to hex color
   */
  _hslToHex(h, s, l) {
    s /= 100;
    l /= 100;
    const a = s * Math.min(l, 1 - l);
    const f = n => {
      const k = (n + h / 30) % 12;
      const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
      return Math.round(255 * color).toString(16).padStart(2, '0');
    };
    return `#${f(0)}${f(8)}${f(4)}`;
  }

  // Color utility functions
  _lightenColor(hex, percent) {
    const num = parseInt(hex.replace('#', ''), 16);
    const amt = Math.round(2.55 * percent);
    const R = Math.min(255, (num >> 16) + amt);
    const G = Math.min(255, (num >> 8 & 0x00FF) + amt);
    const B = Math.min(255, (num & 0x0000FF) + amt);
    return '#' + ((R << 16) + (G << 8) + B).toString(16).padStart(6, '0');
  }

  _darkenColor(hex, percent) {
    const num = parseInt(hex.replace('#', ''), 16);
    const amt = Math.round(2.55 * percent);
    const R = Math.max(0, (num >> 16) - amt);
    const G = Math.max(0, (num >> 8 & 0x00FF) - amt);
    const B = Math.max(0, (num & 0x0000FF) - amt);
    return '#' + ((R << 16) + (G << 8) + B).toString(16).padStart(6, '0');
  }

  _hexToRgb(hex) {
    const num = parseInt(hex.replace('#', ''), 16);
    const r = num >> 16;
    const g = num >> 8 & 0x00FF;
    const b = num & 0x0000FF;
    return `${r}, ${g}, ${b}`;
  }

  _generateAccentColor(primaryHex) {
    // Generate a complementary accent color
    const num = parseInt(primaryHex.replace('#', ''), 16);
    const r = (num >> 16) ^ 0xFF;
    const g = (num >> 8 & 0x00FF) ^ 0xFF;
    const b = (num & 0x0000FF) ^ 0xFF;
    return '#' + ((r << 16) + (g << 8) + b).toString(16).padStart(6, '0');
  }
