  /**
   * Customize Homepage component
   */
  async _customizeHomepage(frontendPath, customizations) {
    try {
      console.log('🏠 Customizing homepage...');

      const homePath = path.join(frontendPath, 'src', 'pages', 'Home.js');
      
      if (!await fs.pathExists(homePath)) {
        console.warn('⚠️  Home.js not found, skipping');
        return;
      }

      let content = await fs.readFile(homePath, 'utf-8');

      // Update welcome text
      content = content.replace(
        /Welcome to.*?(?=<|"|')/g,
        `Welcome to ${customizations.appName}`
      );

      // Update tagline if exists
      if (customizations.brandingChanges.tagline) {
        content = content.replace(
          /(tagline|subtitle|description).*?["'].*?["']/gi,
          `tagline="${customizations.brandingChanges.tagline}"`
        );
      }

      // Add company name
      content = content.replace(
        /Coorg Masala|Coorg Spices/gi,
        customizations.brandingChanges.companyName
      );

      await fs.writeFile(homePath, content);
      console.log('✅ Homepage customized');
    } catch (error) {
      console.warn('⚠️  Failed to customize homepage:', error.message);
    }
  }

