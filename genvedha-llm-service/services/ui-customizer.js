  /**
   * Update App-level configuration
   */
  async _updateAppConfig(frontendPath, customizations) {
    try {
      console.log('⚙️  Updating app configuration...');

      // Update package.json
      const packagePath = path.join(frontendPath, 'package.json');
      if (await fs.pathExists(packagePath)) {
        const packageJson = await fs.readJson(packagePath);
        packageJson.name = customizations.appName.toLowerCase().replace(/\s+/g, '-');
        packageJson.description = customizations.seoConfig?.metaDescription || packageJson.description;
        await fs.writeJson(packagePath, packageJson, { spaces: 2 });
      }

      // Update public/index.html
      const indexPath = path.join(frontendPath, 'public', 'index.html');
      if (await fs.pathExists(indexPath)) {
        let html = await fs.readFile(indexPath, 'utf-8');
        
        // Update title
        html = html.replace(
          /<title>.*?<\/title>/,
          `<title>${customizations.seoConfig?.metaTitle || customizations.appName}</title>`
        );
        
        // Update meta description
        if (html.includes('name="description"')) {
          html = html.replace(
            /name="description" content=".*?"/,
            `name="description" content="${customizations.seoConfig?.metaDescription || ''}"`
          );
        }
        
        await fs.writeFile(indexPath, html);
      }

      console.log('✅ App configuration updated');
    } catch (error) {
      console.warn('⚠️  Failed to update app config:', error.message);
    }
  }

