  /**
   * Apply complete UI customizations to the app
   * @param {Object} params - Customization parameters
   * @param {string} params.appPath - Path to the generated app
   * @param {Object} params.customizations - Customization data from Claude
   * @returns {Promise<Object>} Customization results
   */
  async applyUICustomizations(params) {
    const { appPath, customizations } = params;
    const frontendPath = path.join(appPath, 'frontend');

    try {
      console.log('🎨 Applying UI customizations...');

      const results = {
        filesModified: 0,
        componentsUpdated: [],
        errors: []
      };

      // Check if frontend exists
      if (!await fs.pathExists(frontendPath)) {
        throw new Error('Frontend directory not found');
      }

      // 1. Inject CSS variables and theme
      await this._injectColorTheme(frontendPath, customizations.brandingChanges);
      results.filesModified++;
      results.componentsUpdated.push('CSS Theme');

      // 2. Customize Homepage
      await this._customizeHomepage(frontendPath, customizations);
      results.filesModified++;
      results.componentsUpdated.push('Homepage');

      // 3. Customize Navbar
      await this._customizeNavbar(frontendPath, customizations);
      results.filesModified++;
      results.componentsUpdated.push('Navbar');

      // 4. Customize Footer
      await this._customizeFooter(frontendPath, customizations);
      results.filesModified++;
      results.componentsUpdated.push('Footer');

      // 5. Apply theme to Product Cards
      await this._customizeProductCard(frontendPath, customizations.brandingChanges);
      results.filesModified++;
      results.componentsUpdated.push('ProductCard');

      // 6. Update App-level configuration
      await this._updateAppConfig(frontendPath, customizations);
      results.filesModified++;
      results.componentsUpdated.push('App Config');

      console.log(`✅ UI customizations applied: ${results.filesModified} files modified`);
      return results;

    } catch (error) {
      console.error('❌ Failed to apply UI customizations:', error.message);
      throw error;
    }
  }

